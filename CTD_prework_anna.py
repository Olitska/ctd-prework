# Verification if driver can go back to the depot

truck_number = input("What is the truck number? ")
oil_amount = int(input("How much oil is in the tank? "))

if oil_amount >=2000:
  print(truck_number + " driver you have " + str(oil_amount) + " gallons of oil, so you can go back to the depot.")
else:
  print(truck_number + " driver you have " + str(oil_amount) + " gallons of oil, so you can not go back to the depot.")

